// Regenerates public/games/trivia/questions.js from the Open Trivia Database (https://opentdb.com, CC BY-SA 4.0).
// Run by hand (node scripts/fetch-trivia.mjs); the game never fetches at runtime. OpenTDB allows one request per 5 s.
// Output: a classic script defining TRIVIA_DATA = { cats: [name], q: [[cat, diff 0-2, question, correct, ...wrong]] }.

import { writeFileSync } from 'node:fs';

const OUT = new URL('../public/games/trivia/questions.js', import.meta.url);
const MAX_BYTES = 1_450_000;
const wait = ms => new Promise(r => setTimeout(r, ms));
const get = async (url, tries = 5) => {
  await wait(5200);
  try {
    return await (await fetch(url)).json();
  } catch (err) {
    if (tries <= 1) throw err;
    console.warn('retry', String(err));
    return get(url, tries - 1);
  }
};
const dec = s => decodeURIComponent(s);
const short = name => name.replace(/^(Entertainment|Science): /, '');

const { token } = await get('https://opentdb.com/api_token.php?command=request');
const { trivia_categories: cats } = await (await fetch('https://opentdb.com/api_category.php')).json();
const seen = new Set();
const q = [];
for (const [ci, cat] of cats.entries()) {
  for (let page = 0; page < 40; page++) {
    const res = await get(`https://opentdb.com/api.php?amount=50&category=${cat.id}&encode=url3986&token=${token}`);
    if (res.response_code !== 0) break; // 4: this category is used up for the token
    for (const r of res.results) {
      const text = dec(r.question);
      if (seen.has(text)) continue;
      seen.add(text);
      q.push([ci, ['easy', 'medium', 'hard'].indexOf(dec(r.difficulty)), text, dec(r.correct_answer), ...r.incorrect_answers.map(dec)]);
    }
    console.log(cat.name, q.length);
  }
}
const head = `// Questions from the Open Trivia Database (https://opentdb.com), licensed CC BY-SA 4.0
// (https://creativecommons.org/licenses/by-sa/4.0/). Generated by scripts/fetch-trivia.mjs; entries are unchanged except
// for decoding. This data file is shared under the same license.
// [category index, difficulty 0 easy / 1 medium / 2 hard, question, correct answer, ...wrong answers]
`;
const render = list => `${head}var TRIVIA_DATA = ${JSON.stringify({ cats: cats.map(c => short(c.name)), q: list })};\nglobalThis.TRIVIA_DATA = TRIVIA_DATA;\n`;
let list = q;
// Over budget: drop every 12th question until it fits, so each category keeps its share.
while (Buffer.byteLength(render(list)) > MAX_BYTES) list = list.filter((_, i) => i % 12 !== 11);
writeFileSync(OUT, render(list));
console.log('wrote', list.length, 'questions,', Buffer.byteLength(render(list)), 'bytes');
